KEY_LABELS = ("device_a", "device_b")


def _seed(label: str) -> bytes:
    return hashlib.sha256(f"jeeves/spec/sync/seed/{label}".encode()).digest()


def _member_id(label: str) -> uuid.UUID:
    return uuid.uuid5(JEEVES_WORKSPACE_NAMESPACE, f"spec/member/{label}")


def _op_id(name: str) -> uuid.UUID:
    return uuid.uuid5(JEEVES_WORKSPACE_NAMESPACE, f"spec/op/{name}")


