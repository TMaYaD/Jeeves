def _header_vectors() -> list[dict[str, Any]]:
    """Header-only vectors that pin each field to its offset.

    The probe is deliberately not a servable op: every field carries a distinct
    byte pattern so that a codec reading a field at the wrong offset produces
    visibly wrong bytes rather than a plausible-looking header.
    """
    all_zero = OpHeader(
        suite=0,
        op_class=0,
        workspace_id=uuid.UUID(int=0),
        key_epoch=0,
        op_id=uuid.UUID(int=0),
        author_member_id=uuid.UUID(int=0),
        author_key_id=bytes(8),
        author_seq=0,
    )
    probe = OpHeader(
        suite=0xA1,
        op_class=0xA2,
        workspace_id=uuid.UUID(bytes=b"\x11" * 16),
        key_epoch=0xB3B4B5B6,
        op_id=uuid.UUID(bytes=b"\x22" * 16),
        author_member_id=uuid.UUID(bytes=b"\x33" * 16),
        author_key_id=b"\x44" * 8,
        # Distinct in every byte that can be, and below 2^53 so a JSON reader
        # on a platform without a 64-bit integer type still round-trips it
        # exactly (see MAX_REPRESENTABLE_AUTHOR_SEQ on the Dart side).
        author_seq=0x001F2F3F4F5F6F7F,
        prev_author_hash=b"\x55" * 32,
        observed_head=b"\x66" * 32,
        nonce=b"\x77" * 24,
    )
    return [
        {
            "name": "all_zero_header",
            "note": "158 zero bytes — pins the header length itself.",
            "header": _header_json(all_zero),
            "header_hex": all_zero.serialize().hex(),
        },
        {
            "name": "distinct_field_probe",
            "note": "Every field a distinct byte pattern — pins every offset.",
            "header": _header_json(probe),
            "header_hex": probe.serialize().hex(),
        },
    ]


def _positive_vectors() -> list[dict[str, Any]]:
    vectors: list[dict[str, Any]] = []

    first_header = _header(op_id_name="set_theme_dark", key="device_a", author_seq=1)
    first = _positive(
        "content_set_preference",
        key="device_a",
        header=first_header,
        payload=_theme_payload(key="device_a", value="dark", wall_ms=BASE_WALL_MS).encode(),
        note="The smallest real op: one user_preferences write, body in the 256 class.",
    )
    vectors.append(first)

    chained_header = _header(
        op_id_name="set_theme_light",
        key="device_a",
        author_seq=2,
        prev_author_hash=bytes.fromhex(first["envelope_sha256_hex"]),
    )
    vectors.append(
        _positive(
            "content_chained_author_seq_2",
            key="device_a",
            header=chained_header,
            payload=_theme_payload(
                key="device_a", value="light", wall_ms=BASE_WALL_MS + 1000
            ).encode(),
            note=(
                "author_seq 2 with prev_author_hash = SHA-256 of "
                "content_set_preference's envelope — pins the per-author chain."
            ),
        )
    )

    vectors.append(
        _positive(
            "content_tombstone",
            key="device_b",
            header=_header(op_id_name="delete_theme", key="device_b", author_seq=1),
            payload=OpPayload(
                collection=USER_PREFERENCES_COLLECTION,
                entity_id=THEME_ENTITY_ID,
                hlc=Hlc.for_member(MEMBER_IDS["device_b"], BASE_WALL_MS + 2000),
                tombstone=True,
            ).encode(),
            note="Deletion is an op, never row absence: empty fields plus tombstone.",
        )
    )

    vectors.append(
        _positive(
            "content_per_field_hlc",
            key="device_a",
            header=_header(op_id_name="per_field_hlc", key="device_a", author_seq=3),
            payload=OpPayload(
                collection=USER_PREFERENCES_COLLECTION,
                entity_id=THEME_ENTITY_ID,
                hlc=Hlc.for_member(MEMBER_IDS["device_a"], BASE_WALL_MS + 3000),
                fields={
                    "key": FieldWrite(value=THEME_KEY),
                    "value": FieldWrite(
                        value='"solarized"',
                        hlc=Hlc.for_member(MEMBER_IDS["device_b"], BASE_WALL_MS - 5000),
                    ),
                },
            ).encode(),
            note=(
                "Per-field HLC capability: format now, populated only by "
                "compaction ops (#555) re-asserting original clocks."
            ),
        )
    )

    for index, size_class in enumerate(BODY_SIZE_CLASSES_BYTES):
        vectors.append(
            _positive(
                f"content_body_size_class_{size_class}",
                key="device_a",
                header=_header(
                    op_id_name=f"size_class_{size_class}", key="device_a", author_seq=10 + index
                ),
                payload=_sized_payload(
                    _theme_payload(key="device_a", value="dark", wall_ms=BASE_WALL_MS),
                    size_class - PAYLOAD_LENGTH_PREFIX_BYTES - PADDING_BYTES_IN_SIZE_CLASS_VECTORS,
                ).encode(),
                note=(
                    f"Body padded to the {size_class}-byte size class, "
                    f"{PADDING_BYTES_IN_SIZE_CLASS_VECTORS} padding bytes."
                ),
            )
        )

    oversize_body_length = 2 * BODY_OVERSIZE_MULTIPLE_BYTES
    vectors.append(
        _positive(
            "content_body_oversize_32768",
            key="device_a",
            header=_header(op_id_name="oversize", key="device_a", author_seq=20),
            payload=_sized_payload(
                _theme_payload(key="device_a", value="dark", wall_ms=BASE_WALL_MS),
                oversize_body_length
                - PAYLOAD_LENGTH_PREFIX_BYTES
                - PADDING_BYTES_IN_SIZE_CLASS_VECTORS,
            ).encode(),
            note=(
                "Above the largest size class a body rounds up to the next "
                "16 KiB multiple, with no hard cap."
            ),
        )
    )

    return vectors


