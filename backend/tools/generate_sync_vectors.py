"""Generate the frozen sync golden vectors in ``spec/sync/``.

Run once, by hand, and never again as part of a test or a CI job::

    cd backend && uv run python tools/generate_sync_vectors.py

The point of the vectors is that they are *frozen*: the Python codec and the
Dart codec both assert byte equality against the same committed file, so a
change on either side that the other did not make shows up as a failing test
rather than as two implementations quietly agreeing on something new.  A
generator wired into the test run would defeat that entirely — it would
regenerate the expectation to match whatever the Python side now does.

Re-running this script is therefore a deliberate protocol change.  Expect the
diff to be reviewed as one.
"""

