# --- Reducer vectors --------------------------------------------------------

_HARNESS_COLLECTION = "harness_docs"
_DOC_ID = str(uuid.uuid5(JEEVES_WORKSPACE_NAMESPACE, "spec/entity/harness_doc"))
_MEMBER_A = MEMBER_IDS["device_a"].hex
_MEMBER_B = MEMBER_IDS["device_b"].hex
# device_a and device_b must sort in a known direction for the tie-break case.
_LOWER_MEMBER, _HIGHER_MEMBER = sorted((_MEMBER_A, _MEMBER_B))


def _reduce_op(
    *,
    author: str,
    collection: str = _HARNESS_COLLECTION,
    entity_id: str = _DOC_ID,
    hlc: list[Any],
    fields: dict[str, Any] | None = None,
    tombstone: bool = False,
) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "collection": collection,
        "id": entity_id,
        "fields": fields or {},
        "hlc": hlc,
    }
    if tombstone:
        payload["tombstone"] = True
    return {"author_member_id_hex": author, "payload": payload}


