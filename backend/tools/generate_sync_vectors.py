def _header(
    *,
    op_id_name: str,
    key: str,
    author_seq: int,
    suite: int = SUITE_PLAINTEXT_V1,
    op_class: int = OP_CLASS_CONTENT,
    workspace_id: uuid.UUID = WORKSPACE_ID,
    prev_author_hash: bytes | None = None,
    key_epoch: int = 0,
    nonce: bytes | None = None,
) -> OpHeader:
    sign_pk = bytes(SIGNING_KEYS[key].verify_key)
    return OpHeader(
        suite=suite,
        op_class=op_class,
        workspace_id=workspace_id,
        key_epoch=key_epoch,
        op_id=_op_id(op_id_name),
        author_member_id=MEMBER_IDS[key],
        author_key_id=derive_key_id(sign_pk),
        author_seq=author_seq,
        prev_author_hash=prev_author_hash or bytes(32),
        # Zero under 0x00; an explicit pinned value under 0x01, where it is the
        # XChaCha20 nonce and part of the AAD.  Production draws it from a CSPRNG.
        nonce=nonce if nonce is not None else bytes(24),
    )


def _header_json(header: OpHeader) -> dict[str, Any]:
    return {
        "suite": header.suite,
        "op_class": header.op_class,
        "workspace_id": str(header.workspace_id),
        "key_epoch": header.key_epoch,
        "op_id": str(header.op_id),
        "author_member_id": str(header.author_member_id),
        "author_key_id_hex": header.author_key_id.hex(),
        "author_seq": header.author_seq,
        "prev_author_hash_hex": header.prev_author_hash.hex(),
        "observed_head_hex": header.observed_head.hex(),
        "nonce_hex": header.nonce.hex(),
    }


#: Padding a size-class vector's body carries beyond its framed payload.
#:
#: Spelled out because the note text on those vectors states this number, and the
#: payload length is ``size_class - PAYLOAD_LENGTH_PREFIX_BYTES - this``.  Left as
#: a bare ``- 36`` the two halves could not move together: a change to the prefix
#: width would silently produce vectors whose own notes were wrong.
PADDING_BYTES_IN_SIZE_CLASS_VECTORS = 32


def _sized_payload(base: OpPayload, target_payload_length: int) -> OpPayload:
    """``base`` grown with an ASCII filler field to exactly the target length."""
    probe = replace(base, fields={**base.fields, "filler": FieldWrite(value="")})
    padding_needed = target_payload_length - len(probe.encode())
    if padding_needed < 0:
        raise ValueError(f"base payload already exceeds {target_payload_length} bytes")
    return replace(base, fields={**base.fields, "filler": FieldWrite(value="x" * padding_needed)})


def _positive(
    name: str,
    *,
    key: str,
    header: OpHeader,
    payload: bytes,
    note: str,
) -> dict[str, Any]:
    body = frame_body(payload)
    envelope = build_envelope(header, body, SIGNING_KEYS[key])
    return {
        "name": name,
        "note": note,
        "key": key,
        "header": _header_json(header),
        "header_hex": header.serialize().hex(),
        "payload_json": payload.decode("utf-8"),
        "payload_length_bytes": len(payload),
        "body_length_bytes": len(body),
        "body_hex": body.hex(),
        "signature_hex": envelope[-SIGNATURE_LENGTH_BYTES:].hex(),
        "envelope_hex": envelope.hex(),
        "envelope_sha256_hex": envelope_hash(envelope).hex(),
    }


def _negative(
    name: str,
    *,
    key: str,
    reason: str,
    envelope: bytes,
    note: str,
    expected_workspace_id: uuid.UUID = WORKSPACE_ID,
) -> dict[str, Any]:
    return {
        "name": name,
        "note": note,
        "key": key,
        "reason": reason,
        "expected_workspace_id": str(expected_workspace_id),
        "envelope_hex": envelope.hex(),
    }


def _theme_payload(*, key: str, value: str, wall_ms: int, counter: int = 0) -> OpPayload:
    return OpPayload(
        collection=USER_PREFERENCES_COLLECTION,
        entity_id=THEME_ENTITY_ID,
        hlc=Hlc.for_member(MEMBER_IDS[key], wall_ms, counter),
        fields={
            "key": FieldWrite(value=THEME_KEY),
            "value": FieldWrite(value=json.dumps(value)),
        },
    )


