    for filename, document in (
        ("envelope_v1_vectors.json", _envelope_vectors_document()),
        ("reducer_v1_vectors.json", _reducer_vectors_document()),
    ):
        path = SPEC_DIR / filename
        path.write_text(json.dumps(document, indent=2, sort_keys=False) + "\n")
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        print(f"{path.relative_to(SPEC_DIR.parents[1])}  sha256={digest}")


