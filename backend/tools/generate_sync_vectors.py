def _pref_op(
    *,
    author: str,
    wall_ms: int,
    counter: int = 0,
    entity_id: str = _SNOOZE_ENTITY_ID,
    key: str | None = _SNOOZE_KEY,
    value: str | None = None,
    tombstone: bool = False,
) -> dict[str, Any]:
    fields: dict[str, Any] = {}
    if key is not None:
        fields["key"] = {"v": key}
    if value is not None:
        fields["value"] = {"v": value}
    return _reduce_op(
        author=author,
        collection=USER_PREFERENCES_COLLECTION,
        entity_id=entity_id,
        hlc=[wall_ms, counter, author],
        fields=fields,
        tombstone=tombstone,
    )


def _reduce_op(
    *,
    author: str,
    collection: str = _HARNESS_COLLECTION,
    entity_id: str = _DOC_ID,
    hlc: list[Any],
    fields: dict[str, Any] | None = None,
    tombstone: bool = False,
) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "collection": collection,
        "id": entity_id,
        "fields": fields or {},
        "hlc": hlc,
    }
    if tombstone:
        payload["tombstone"] = True
    return {"author_member_id_hex": author, "payload": payload}


